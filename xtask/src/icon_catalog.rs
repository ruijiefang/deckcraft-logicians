//! Offline, deterministic conversion of pinned Font Awesome Free metadata. No web assets or fonts.
use sha2::{Digest, Sha256};
use std::{collections::BTreeMap, path::Path};

use i_overlay::{core::fill_rule::FillRule, float::simplify::SimplifyShape};
use kurbo::{BezPath, PathEl};
use serde_json::Value;

const REV: &str = "41cfe644047fc3a4c49c22acc721cacc3e1021fe";
const INPUTS: [(&str, &str); 3] = [
    ("icons.json", "1de0b31da59a209788e3353e01a1d91da4374619a283718f173d4e901750ff40"),
    ("categories.yml", "817e18cf50580a3f44823d6a080949f679921b73682ae1ab90ba776af8f7ed58"),
    ("LICENSE.txt", "329f24fdba0c57714d7d202d30a74767feac6907685ee24f0abbf1bd47581a07"),
];

pub fn run(args: &[&str]) -> Result<(), String> {
    let [source, output] = args else { return Err("usage: cargo xtask icons SOURCE OUTPUT (see docs/icons.md)".into()) };
    let source = Path::new(source);
    let mut inputs = BTreeMap::new();
    for (name, hash) in INPUTS {
        let path = source.join(name);
        let bytes = read_bounded(&path, 16 * 1024 * 1024)?;
        if format!("{:x}", Sha256::digest(&bytes)) != hash {
            return Err(format!("{}: expected Font Awesome Free 7.1.0 ({REV}), SHA-256 {hash}", path.display()));
        }
        inputs.insert(name, bytes);
    }
    let input = inputs.get("icons.json").ok_or("missing icons.json")?;
    let icons: BTreeMap<String, Value> = serde_json::from_slice(input).map_err(|e| e.to_string())?;
    if icons.len() > 10_000 {
        return Err("too many icons".into());
    }
    let categories = categories(std::str::from_utf8(inputs.get("categories.yml").ok_or("missing categories.yml")?).map_err(|e| e.to_string())?)?;
    let mut out = format!(
        "// @generated by cargo xtask icons; Font Awesome Free 7.1.0, commit {REV}.\n// Fonticons, Inc.; CC-BY-4.0. Paths converted; winding normalized where necessary.\n// See assets/licenses/fontawesome-7.1.0.txt, NOTICE, ATTRIBUTION.md and docs/icons.md.\n#[rustfmt::skip]\nstatic FONT_AWESOME: [Icon; ICON_COUNT] = [\n"
    );
    let mut count = 0;
    let mut normalized = 0;
    for (name, icon) in icons {
        if name.len() > 128 || !name.bytes().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == b'-') {
            return Err("invalid icon id".into());
        }
        for style in ["solid", "regular"] {
            if !icon["free"].as_array().is_some_and(|a| a.iter().any(|s| s == style)) {
                continue;
            }
            let svg = &icon["svg"][style];
            let path = svg["path"].as_str().ok_or_else(|| format!("{name}: missing path"))?;
            let width = svg["width"].as_f64().filter(|w| w.is_finite() && *w > 0.0 && *w <= 4096.0).ok_or("invalid width")?;
            let height = svg["height"].as_f64().filter(|h| h.is_finite() && *h > 0.0 && *h <= 4096.0).ok_or("invalid height")?;
            let (path, changed) = normalize(path).map_err(|e| format!("{name}/{style}: {e}"))?;
            normalized += usize::from(changed);
            let label = icon["label"].as_str().ok_or("missing label")?;
            let mut terms = strings(&icon["search"]["terms"]);
            terms.extend(strings(&icon["aliases"]["names"]));
            terms.sort();
            terms.dedup();
            let cats = categories.get(&name).cloned().unwrap_or_else(|| vec!["Other".into()]);
            out.push_str(&format!("    Icon {{ name: {id:?}, label: {label:?}, category: {cat:?}, stroke: 0.0, d: {path:?}, collection: \"Font Awesome\", style: {style:?}, view: [{width:?}, {height:?}], terms: {terms:?}, categories: &{cats:?}, cache: OnceLock::new(), search: OnceLock::new() }},\n", id=format!("fontawesome:{style}:{name}"), cat=cats.first().ok_or("empty categories")?, terms=terms.join(" ")));
            count += 1;
        }
    }
    out.push_str("];\n");
    if count == 0 {
        return Err("empty free catalogue".into());
    }
    std::fs::write(output, out.replace("ICON_COUNT", &count.to_string())).map_err(|e| e.to_string())?;
    println!("{count} Free Solid/Regular icons; {normalized} winding conversions; Brands excluded");
    Ok(())
}

fn read_bounded(path: &Path, max: u64) -> Result<Vec<u8>, String> {
    use std::io::Read;
    let file = std::fs::File::open(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let mut bytes = Vec::new();
    file.take(max + 1).read_to_end(&mut bytes).map_err(|e| e.to_string())?;
    if bytes.len() as u64 > max {
        return Err(format!("{}: file exceeds {max} bytes", path.display()));
    }
    Ok(bytes)
}

fn strings(v: &Value) -> Vec<String> {
    v.as_array().into_iter().flatten().filter_map(Value::as_str).map(str::to_owned).collect()
}

// Parse only the small, fixed upstream categories schema. Unexpected syntax fails regeneration.
fn categories(text: &str) -> Result<BTreeMap<String, Vec<String>>, String> {
    let mut out: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut names = Vec::new();
    for line in text.lines().filter(|s| !s.trim().is_empty()) {
        if !line.starts_with(' ') && line.ends_with(':') {
            names.clear();
        } else if let Some(name) = line.strip_prefix("    - ") {
            names.push(name.trim_matches('\'').to_string());
        } else if let Some(label) = line.strip_prefix("  label: ") {
            for name in &names {
                out.entry(name.clone()).or_default().push(label.trim_matches('\'').to_string());
            }
        } else if line != "  icons:" {
            return Err(format!("unexpected category metadata: {line}"));
        }
    }
    Ok(out)
}

/// Retain curves when nonzero and even-odd agree. Otherwise resolve overlaps with the existing
/// polygon overlay library. 0.05 source units is under 0.01 pt at the default insertion size.
fn normalize(d: &str) -> Result<(String, bool), String> {
    if d.len() > 128 * 1024 {
        return Err("path too large".into());
    }
    let path = BezPath::from_svg(d).map_err(|e| e.to_string())?;
    if path.elements().len() > 20_000 || !path.is_finite() {
        return Err("invalid or excessive path".into());
    }
    let mut contours: Vec<Vec<[f64; 2]>> = Vec::new();
    let mut current = Vec::new();
    kurbo::flatten(path.iter(), 0.05, |el| match el {
        PathEl::MoveTo(p) => {
            if !current.is_empty() {
                contours.push(std::mem::take(&mut current));
            }
            current.push([p.x, p.y]);
        }
        PathEl::LineTo(p) => current.push([p.x, p.y]),
        PathEl::ClosePath if !current.is_empty() => {
            contours.push(std::mem::take(&mut current));
        }
        _ => {}
    });
    if !current.is_empty() {
        contours.push(current);
    }
    if contours.iter().map(Vec::len).sum::<usize>() > 100_000 {
        return Err("too many flattened points".into());
    }
    let nonzero = contours.simplify_shape(FillRule::NonZero);
    if nonzero.is_empty() {
        return Err("empty silhouette".into());
    }
    if nonzero == contours.simplify_shape(FillRule::EvenOdd) {
        return Ok((path.to_svg(), false));
    }
    let mut resolved = BezPath::new();
    for contour in nonzero.iter().flatten() {
        if let Some((first, rest)) = contour.split_first() {
            resolved.move_to((first[0], first[1]));
            for p in rest {
                resolved.line_to((p[0], p[1]));
            }
            resolved.close_path();
        }
    }
    Ok((resolved.to_svg(), true))
}

#[cfg(test)]
mod tests {
    use super::*;
    use kurbo::{Point, Shape};
    #[test]
    fn overlapping_contours_and_holes_keep_nonzero_coverage() {
        let (d, changed) = normalize("M0 0H10V10H0Z M5 0H15V10H5Z").unwrap();
        assert!(changed);
        let p = BezPath::from_svg(&d).unwrap();
        assert_eq!(p.winding(Point::new(7.0, 5.0)).abs() % 2, 1);
        let (d, _) = normalize("M0 0H10V10H0Z M2 2V8H8V2Z").unwrap();
        assert_eq!(BezPath::from_svg(&d).unwrap().winding(Point::new(5.0, 5.0)), 0);
        assert!(normalize("MNaN 0").is_err());
    }
    #[test]
    fn categories_retain_multiple_memberships() {
        let cats = categories("a:\n  icons:\n    - house\n  label: Buildings\nb:\n  icons:\n    - house\n  label: Home\n").unwrap();
        assert_eq!(cats["house"], ["Buildings", "Home"]);
        assert!(categories("  unexpected: true").is_err());
    }
}
